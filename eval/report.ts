#!/usr/bin/env bun
// eval/report.ts — build eval/results/<run>/REPORT.md from scores/*/scores.json, the builds'
// progress.jsonl/build.log, noise.json, and the hand-written NOTES.md (Phase 0 fixes, lessons).
//
//   bun run eval:report --run <run>
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { CRITERIA, type Criterion } from "./lib/criteria";
import { distribution, poolKeyQuestion, worstSlides, mean, type DeckScores, type NoiseRow } from "./lib/aggregate";
import { costUsd, fmtUsd } from "../src/agent/pricing";
import { addUsage, ZERO_USAGE, type TokenUsage } from "../src/agent/usage";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const i = process.argv.indexOf("--run");
const RUN = i >= 0 ? process.argv[i + 1] : readdirSync(join(ROOT, "eval", "results")).filter((d) => /baseline/.test(d)).sort().pop()!;
const RUN_DIR = join(ROOT, "eval", "results", RUN);
const MODEL = "claude-opus-5-5";

const SHORT: Record<Criterion, string> = {
  claim_at_rest: "claim", mechanism_shown: "mech", device_works: "device", fidelity: "fidelity", craft: "craft", not_generic: "!generic",
};

interface BuildStats { wallMs?: number; planMs?: number; costUsd?: number; planCostUsd?: number; passes: Record<string, number>; sealedPass1Clean: number; budgetHit: number; retries: number }

/** Wall time, cost and per-slide pass counts from a build's progress.jsonl (+ build.log cost lines). */
export function buildStats(stem: string): BuildStats | undefined {
  const progress = join(RUN_DIR, `${stem}.progress.jsonl`);
  if (!existsSync(progress)) return undefined;
  const s: BuildStats = { passes: {}, sealedPass1Clean: 0, budgetHit: 0, retries: 0 };
  let usage: TokenUsage = ZERO_USAGE;
  for (const line of readFileSync(progress, "utf8").split("\n")) {
    if (!line.trim()) continue;
    const e = JSON.parse(line);
    if (e.type === "slide_done") {
      const ps = e.timing?.passes ?? [];
      s.passes[e.id] = ps.length;
      const last = ps[ps.length - 1];
      if (ps.length === 1 && last && last.overflowPx <= 2 && last.consoleErrors === 0) s.sealedPass1Clean++;
      if (ps.length >= 4) s.budgetHit++;
    }
    if (e.type === "slide_retry") s.retries++;
    if (e.type === "deck_done") { s.wallMs = e.totalMs; usage = addUsage(usage, e.usage ?? ZERO_USAGE); }
  }
  s.costUsd = costUsd(usage, MODEL);
  const log = join(RUN_DIR, `${stem}.build.log`);
  if (existsSync(log)) {
    // `mindsizer plan` prints its own cost line before `build` starts; the last cost line is the build's.
    const costs = [...readFileSync(log, "utf8").matchAll(/cost \(API-equiv · est\):\s+~\$([\d.]+)/g)].map((m) => Number(m[1]));
    if (costs.length >= 2) s.planCostUsd = costs[0];
    if (costs.length) s.costUsd = costs[costs.length - 1];
  }
  const planMs = join(RUN_DIR, `${stem}.plan-ms.txt`);
  if (existsSync(planMs)) s.planMs = Number(readFileSync(planMs, "utf8"));
  return s;
}

function loadDecks(dir: string): DeckScores[] {
  const p = join(RUN_DIR, dir);
  if (!existsSync(p)) return [];
  return readdirSync(p)
    .filter((d) => existsSync(join(p, d, "scores.json")))
    .map((d) => ({ ...JSON.parse(readFileSync(join(p, d, "scores.json"), "utf8")), _dir: `${dir}/${d}` }));
}

const f = (n: number | null | undefined, d = 2) => (n === null || n === undefined ? "–" : n.toFixed(d));
const mins = (ms?: number) => (ms ? `${(ms / 60000).toFixed(1)} min` : "–");

function deckName(d: any): string { return String(d._dir).split("/").pop()!; }
function isReference(d: any): boolean { return deckName(d).startsWith("ref-"); }

function main() {
  const decks = loadDecks("scores");
  const r2 = loadDecks("scores-r2");
  if (!decks.length) throw new Error(`no scores under ${RUN_DIR}/scores`);
  const baseline = decks.filter((d) => !isReference(d));
  const out: string[] = [];
  const status = existsSync(join(RUN_DIR, "sources-status.json")) ? JSON.parse(readFileSync(join(RUN_DIR, "sources-status.json"), "utf8")) : {};

  out.push(`# Baseline eval — current harness, every role on Opus 5.5`, "");
  out.push(`_Run \`${RUN}\` · harness roles: \`${MODEL}\` (default efforts) · judges: \`${(decks[0] as any).judge?.model ?? MODEL}\` (${(decks[0] as any).judge?.effort ?? "medium"}) · generated by \`bun run eval:report --run ${RUN}\`._`, "");
  out.push(`Rubric: [eval/RUBRIC.md](../../RUBRIC.md). Scores are 1–4 (pass ≥ 3); "–" = not applicable or unknown. Screenshots for every slide are under \`scores/<deck>/shots/\`.`, "");

  // ——— key question first: it's the number the redesign targets ———
  const kq = poolKeyQuestion(baseline.map((d) => d.summary!.keyQuestion));
  const kqRef = decks.filter(isReference).map((d) => d.summary!.keyQuestion);
  out.push(`## The key question`, "");
  out.push(`**Of the ${kq.gatePassed} Opus 5.5 slides that passed the harness's mechanical gate (0 overflow, 0 console errors), ${kq.failedKey} (${f((kq.rate ?? 0) * 100, 0)}%) scored < 3 on claim_at_rest, mechanism_shown or device_works.**`, "");
  out.push(`By criterion (a slide can fail several): ${Object.entries(kq.byCriterion).map(([c, n]) => `${c} ${n}`).join(" · ") || "none"}.`);
  if (kqRef.length) {
    const k = poolKeyQuestion(kqRef);
    out.push(`Opus 4.8 reference deck (outline-only, no plan): ${k.failedKey} of ${k.gatePassed} gate-passing slides (${f((k.rate ?? 0) * 100, 0)}%).`);
  }
  out.push("");

  // ——— summary table ———
  out.push(`## Summary`, "");
  out.push(`| deck | slides | ${CRITERIA.map((c) => SHORT[c]).join(" | ")} | coherence | quiz | gate pass | wall | cost (API-eq) |`);
  out.push(`|---|---|${CRITERIA.map(() => "---").join("|")}|---|---|---|---|---|`);
  for (const d of decks) {
    const s = d.summary!;
    const stem = isReference(d) ? undefined : deckName(d);
    const b = stem ? buildStats(stem) : undefined;
    const q = d.deckCriteria.quiz;
    const wall = b ? `${mins(b.wallMs)}${b.planMs ? ` + plan ${mins(b.planMs)}` : ""}` : "–";
    const cost = b?.costUsd !== undefined ? `${fmtUsd(b.costUsd)}${b.planCostUsd ? ` + plan ${fmtUsd(b.planCostUsd)}` : ""}` : "– (built earlier on Opus 4.8)";
    out.push(`| ${deckName(d)} | ${s.slides} | ${CRITERIA.map((c) => f(s.means[c])).join(" | ")} | ${f(s.coherence, 0)} | ${q?.score !== null && q?.score !== undefined ? `${q.correct}/${q.total} (+${q.partial} partial)` : "–"} | ${s.gatePassed}/${s.slides} | ${wall} | ${cost} |`);
  }
  out.push("");
  out.push(`Pass rate (share of judged slides scoring ≥ 3), Opus 5.5 decks pooled: ${CRITERIA.map((c) => {
    const xs = baseline.flatMap((d) => d.slides.map((s) => s.criteria[c]?.score).filter((v): v is 1 | 2 | 3 | 4 => typeof v === "number"));
    return `${SHORT[c]} ${xs.length ? Math.round((xs.filter((x) => x >= 3).length / xs.length) * 100) : "–"}%`;
  }).join(" · ")}.`, "");
  const evalCost = decks.reduce((a, d: any) => a + (d.evalCost?.usd ?? 0), 0) + r2.reduce((a, d: any) => a + (d.evalCost?.usd ?? 0), 0);
  const calls = [...decks, ...r2].reduce((a, d: any) => a + (d.evalCost?.judgeCalls ?? 0), 0);
  out.push(`Scoring cost: ${calls} judge calls, ~${fmtUsd(evalCost)} API-equivalent across ${decks.length + r2.length} scorings.`, "");

  // harness behaviour from progress.jsonl
  out.push(`### How the harness sealed these slides`, "");
  out.push(`| deck | slides | sealed on pass 1 (clean, model never saw a screenshot) | hit the 4-pass budget | content-gate retries | passes per slide |`);
  out.push(`|---|---|---|---|---|---|`);
  for (const d of baseline) {
    const b = buildStats(deckName(d));
    if (!b) continue;
    const ps = Object.values(b.passes);
    out.push(`| ${deckName(d)} | ${ps.length} | ${b.sealedPass1Clean} | ${b.budgetHit} | ${b.retries} | mean ${f(mean(ps), 1)} (${ps.join(", ")}) |`);
  }
  out.push("");

  // ——— distributions ———
  out.push(`## Per-criterion distribution (all Opus 5.5 slides pooled)`, "");
  const allSlides = baseline.flatMap((d) => d.slides);
  out.push(`| criterion | 1 | 2 | 3 | 4 | unknown | n/a | mean |`);
  out.push(`|---|---|---|---|---|---|---|---|`);
  for (const c of CRITERIA) {
    const h = distribution(allSlides, c);
    const xs = allSlides.map((s) => s.criteria[c]?.score).filter((v): v is 1 | 2 | 3 | 4 => typeof v === "number");
    out.push(`| ${c} | ${h["1"]} | ${h["2"]} | ${h["3"]} | ${h["4"]} | ${h.unknown} | ${h["n/a"]} | ${f(mean(xs))} |`);
  }
  out.push("");
  const ref = decks.filter(isReference);
  if (ref.length) {
    out.push(`Opus 4.8 reference deck:`, "");
    out.push(`| criterion | 1 | 2 | 3 | 4 | unknown | n/a |`);
    out.push(`|---|---|---|---|---|---|---|`);
    for (const c of CRITERIA) {
      const h = distribution(ref.flatMap((d) => d.slides), c);
      out.push(`| ${c} | ${h["1"]} | ${h["2"]} | ${h["3"]} | ${h["4"]} | ${h.unknown} | ${h["n/a"]} |`);
    }
    out.push("");
  }

  // deterministic craft numbers
  out.push(`### Deterministic craft checks (raw)`, "");
  out.push(`| deck | slides w/ overflow | console errors | overlapping text pairs | text outside frame | AA contrast failures (slides) | min contrast |`);
  out.push(`|---|---|---|---|---|---|---|`);
  for (const d of decks) {
    const m = d.slides.map((s: any) => s.craftMetrics);
    const mins = m.map((x: any) => x.contrast.minRatio).filter((x: any) => x !== null);
    out.push(`| ${deckName(d)} | ${m.filter((x: any) => x.overflowPx > 2).length} | ${m.reduce((a: number, x: any) => a + x.consoleErrors.length, 0)} | ${m.reduce((a: number, x: any) => a + x.overlaps.length, 0)} | ${m.reduce((a: number, x: any) => a + x.outsideFrame.length, 0)} | ${m.reduce((a: number, x: any) => a + x.contrast.fails.length, 0)} (${m.filter((x: any) => x.contrast.fails.length).length}) | ${mins.length ? Math.min(...mins).toFixed(2) : "–"} |`);
  }
  out.push("");

  // ——— worst slides ———
  out.push(`## The 5 worst slides`, "");
  for (const w of worstSlides(decks as any, 5)) {
    const d = decks.find((x) => x.slides.includes(w.slide))!;
    const s: any = w.slide;
    out.push(`### ${deckName(d)} · ${s.id} — “${s.title}” (sum ${w.total})`, "");
    out.push(`![${s.id}](${(d as any)._dir}/${s.shots.rest})`, "");
    out.push(`Gate: ${s.gate.passed ? "passed" : "FAILED"} (overflow ${s.gate.overflowPx}px, ${s.gate.consoleErrors} errors) · kind: ${s.kind}${s.intent?.claim ? ` · planned claim: “${s.intent.claim}”` : ""}`, "");
    for (const c of CRITERIA) {
      const r: any = s.criteria[c];
      if (!r || r.na) continue;
      const ev = (r.evidence ?? []).slice(0, 2).map((e: string) => `“${e}”`).join("; ");
      out.push(`- **${c}: ${r.score ?? "unknown"}**${r.capped ? ` (capped: ${r.capped.join(", ")})` : ""} — ${String(r.reasoning ?? r.error ?? "").replace(/\n/g, " ")}${ev ? ` Evidence: ${ev}` : ""}${c === "claim_at_rest" && r.read_claim ? ` Read at rest: “${r.read_claim}”` : ""}`);
    }
    out.push("");
  }

  // ——— quiz detail ———
  out.push(`## Comprehension quiz detail`, "");
  for (const d of decks) {
    const q: any = d.deckCriteria.quiz;
    if (!q?.items) continue;
    out.push(`**${deckName(d)}** — ${q.correct}/${q.total} correct, ${q.partial} partial (lenient ${f(q.lenient)})`, "");
    out.push(`| q | kind | grade | question | reader's answer (deck only) |`);
    out.push(`|---|---|---|---|---|`);
    for (const it of q.items) out.push(`| ${it.id} | ${it.kind} | ${it.grade} | ${it.q.replace(/\|/g, "/")} | ${String(it.answer ?? "").replace(/\|/g, "/").replace(/\n/g, " ")} |`);
    out.push("");
  }

  // ——— noise ———
  const noisePath = join(RUN_DIR, "noise.json");
  out.push(`## Judge noise`, "");
  if (existsSync(noisePath)) {
    const n = JSON.parse(readFileSync(noisePath, "utf8"));
    out.push(`Each of ${n.decks.join(", ")} was scored twice by the full scorer (independent judge sessions). Per-criterion disagreement (\`pairs\` = slides judged, not n/a or unknown, in both runs):`, "");
    out.push(`| criterion | pairs | same | ±1 | ±2+ | crossed pass line | mean abs Δ | flip rate | trustworthy? |`);
    out.push(`|---|---|---|---|---|---|---|---|---|`);
    for (const r of n.rows as NoiseRow[]) {
      out.push(`| ${r.criterion} | ${r.pairs} | ${r.exact} | ${r.flip1} | ${r.flip2plus} | ${r.passFlip} | ${f(r.meanAbsDelta)} | ${r.flipRate === null ? "–" : `${Math.round(r.flipRate * 100)}%`} | ${r.trustworthy ? "yes" : "**no**"} |`);
    }
    out.push("");
    for (const dd of n.deckLevel ?? []) out.push(`- ${dd.deck}: coherence ${dd.coherence.join(" → ")}, quiz ${dd.quiz.join(" → ")}`);
    out.push("");
    out.push(`"Trustworthy" = flips by ≥ 1 point on fewer than a third of slides and never by ≥ 2.`, "");
  } else {
    out.push(`_noise.json missing — run \`bun run eval:noise --run ${RUN}\`._`, "");
  }

  // ——— sources ———
  out.push(`## Sources`, "");
  out.push(`| source | status |`);
  out.push(`|---|---|`);
  for (const [id, st] of Object.entries<any>(status)) out.push(`| ${id} | ${st.status === "ok" ? `ok (${st.words} words)` : `unavailable — ${String(st.reason).split(" | ")[0].slice(0, 140)}`} |`);
  out.push("");

  const notes = join(RUN_DIR, "NOTES.md");
  if (existsSync(notes)) out.push(readFileSync(notes, "utf8"));

  writeFileSync(join(RUN_DIR, "REPORT.md"), out.join("\n") + "\n");
  console.log(`✓ wrote ${join("eval", "results", RUN, "REPORT.md")}`);
}

main();
